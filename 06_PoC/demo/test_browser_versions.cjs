const { chromium } = require('playwright');
const { strict: assert } = require('node:assert');
(async()=>{
  const browser=await chromium.launch({headless:true,...(process.env.STTP_BROWSER_PATH ? {executablePath:process.env.STTP_BROWSER_PATH} : {})});
  try {
    const context=await browser.newContext({viewport:{width:1440,height:900}});
    const events=[];
    await context.route('**/demo/api/metrics/event', async route=>{
      events.push(JSON.parse(route.request().postData()));
      await route.fulfill({status:204,headers:{'Access-Control-Allow-Origin':route.request().headers()['origin']||'http://127.0.0.1:8773'}});
    });
    await context.route('**/demo/api/metrics',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({items:[{version:'explore',event:'enter',count:3,seconds:0},{version:'engineering',event:'visible_seconds',count:1,seconds:120}]})}));
    const page=await context.newPage(), errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.goto('http://127.0.0.1:8773/demo/');
    await page.getByRole('button',{name:'试用统计：关'}).waitFor();
    const exploreBox=await page.getByRole('button',{name:'探索版',exact:true}).boundingBox();
    const engineeringBox=await page.getByRole('link',{name:'工程版',exact:true}).boundingBox();
    assert.ok(engineeringBox.y > exploreBox.y);
    assert.equal(exploreBox.x,engineeringBox.x);
    await page.locator('.side-version-switch').screenshot({path:require('node:path').join(require('node:os').tmpdir(),'version-switch-preview.png')});
    await page.setViewportSize({width:390,height:844});
    const mobileExplore=await page.getByRole('button',{name:'探索版',exact:true}).boundingBox();
    const mobileEngineering=await page.getByRole('link',{name:'工程版',exact:true}).boundingBox();
    assert.equal(mobileExplore.y,mobileEngineering.y);
    await page.setViewportSize({width:1440,height:900});
    await page.getByRole('link',{name:'工程版',exact:true}).click();
    await page.getByRole('link',{name:'← 探索版'}).waitFor();
    assert.equal(events.length,0, 'default-off should not send events');
    await page.getByRole('link',{name:'← 探索版'}).click();
    await page.getByRole('button',{name:'试用统计：关'}).click();
    await page.getByRole('button',{name:'试用统计：开'}).waitFor();
    await page.getByRole('button',{name:'探索版',exact:true}).click();
    await page.getByRole('button',{name:'查看统计'}).click();
    await page.getByText(/探索版：进入 3 次/).waitFor();
    await page.getByRole('button',{name:'关闭统计'}).click();
    await page.waitForTimeout(1200);
    await page.getByRole('link',{name:'工程版',exact:true}).click();
    await page.getByRole('button',{name:'试用统计：开'}).waitFor();
    await page.locator('#task-q').waitFor({timeout:30000});
    await page.screenshot({path:require('node:path').join(require('node:os').tmpdir(),'engineering-entry.png')});
    await page.locator('#task-q').fill('water');
    await page.locator('#task-search').click();
    await page.locator('#task-cands .cand-item').first().waitFor({timeout:30000});
    await page.locator('#task-cands .cand-item').first().click();
    await page.locator('#task-run').click();
    await page.locator('#task-entry').waitFor({state:'hidden',timeout:30000});
    await page.getByRole('link',{name:'反馈',exact:true}).click();
    await page.getByRole('heading',{name:'分享你的想法'}).waitFor();
    await page.getByRole('button',{name:'关闭',exact:true}).click();
    await page.getByRole('button',{name:'试用统计：开'}).waitFor();
    await page.getByRole('button',{name:'试用统计：开'}).click();
    await page.getByRole('button',{name:'试用统计：关'}).waitFor();
    assert.ok(events.some(e=>e.version==='explore'&&e.event==='switch_to_engineering'));
    assert.ok(events.some(e=>e.version==='explore'&&e.event==='select_explore'));
    assert.ok(events.some(e=>e.version==='engineering'&&e.event==='enter'));
    assert.ok(events.some(e=>e.version==='engineering'&&e.event==='switch_to_explore'));
    assert.ok(events.some(e=>e.version==='engineering'&&e.event==='search'));
    assert.ok(events.some(e=>e.version==='engineering'&&e.event==='graph_generate'));
    assert.ok(events.some(e=>e.version==='engineering'&&e.event==='feedback_open'));
    assert.ok(events.some(e=>e.version==='explore'&&e.event==='visible_seconds'));
    assert.ok(events.every(e=>Object.keys(e).every(k=>['version','event','seconds'].includes(k))));
    await page.waitForTimeout(500);
    const count=events.length;
    await page.getByRole('button',{name:/发现/}).click();
    await page.waitForTimeout(300);
    assert.equal(events.length,count,'opt-out should stop subsequent events');
    assert.deepEqual(errors,[]);
    console.log('PASS: version switching, default opt-out, opt-in, aggregate payload, visible time, summary, opt-out');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
